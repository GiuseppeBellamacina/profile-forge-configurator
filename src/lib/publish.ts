// Everything needed to put the card on a user's GitHub: file generators + a small GitHub REST client.
// No backend: the user's token stays in the page and only talks to api.github.com.

export const ACTION_REPO = "GiuseppeBellamacina/profile-forge";
const API = "https://api.github.com";
const enc = new TextEncoder();
const dec = new TextDecoder();

export type Raw = Record<string, any>;
export type FileEntry = { path: string; content: string | Uint8Array | null; binary?: boolean; readme?: boolean };

export const toBytes = (s: string | Uint8Array) => (typeof s === "string" ? enc.encode(s) : s);
export function b64(bytes: Uint8Array) {
  let s = "";
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(s);
}
export const fromB64 = (s: string) => Uint8Array.from(atob(s.replace(/\n/g, "")), (c) => c.charCodeAt(0));

export const slug = (s: string) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-");

// ── file generators ──────────────────────────────────────────────────────────

export function workflowYaml({ ref = "v1", hour = 3, onConfigChange = true }: { ref?: string; hour?: number; onConfigChange?: boolean } = {}) {
  return `# Generated by the profile-forge configurator.
# Rebuilds your profile card every day${onConfigChange ? " and whenever config.json changes" : ""}. Run it by hand from the Actions tab.
name: profile-forge

on:
  schedule:
    - cron: "17 ${hour} * * *"
  workflow_dispatch:
${onConfigChange ? "  push:\n    paths: [config.json]\n" : ""}
permissions:
  contents: write

jobs:
  card:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - uses: ${ACTION_REPO}@${ref}
        with:
          # Optional: add a classic PAT (read:user + repo) as the secret PROFILE_FORGE_TOKEN
          # to count private contributions. Without it the default token is used.
          token: \${{ secrets.PROFILE_FORGE_TOKEN || github.token }}
          output_dir: assets
          # Everything else lives in config.json at the root of this repo.

      - name: Commit if changed
        run: |
          git config user.name "github-actions[bot]"
          git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
          git add assets
          git diff --cached --quiet || (git commit -m "chore: refresh profile card" && git pull --rebase && git push)
`;
}

export const configJson = (raw: Raw) =>
  JSON.stringify({ $schema: `https://raw.githubusercontent.com/${ACTION_REPO}/main/config.schema.json`, ...raw }, null, 2) + "\n";

export const MARK = ["<!-- profile-forge:start -->", "<!-- profile-forge:end -->"];

/** The README block: the card (dark/light <picture>) plus one clickable button per link. */
export function readmeBlock(raw: Raw) {
  const slots = Object.keys(raw.themes && !Array.isArray(raw.themes) ? raw.themes : { dark: 1, light: 1 });
  const img = (s: string) => `assets/profile-forge-${s}.svg`;
  const pic = (file: (s: string) => string, alt: string, w = "") => {
    const has = (s: string) => slots.includes(s);
    if (has("dark") && has("light"))
      return `<picture>\n  <source media="(prefers-color-scheme: dark)" srcset="${file("dark")}">\n  <img src="${file("light")}" alt="${alt}"${w}>\n</picture>`;
    return `<img src="${file(slots[0])}" alt="${alt}"${w}>`;
  };
  const buttons = (raw.links ?? [])
    .map((l: Raw) => `<a href="${l.url}">${pic((s: string) => `assets/buttons/${slug(l.label)}-${s}.svg`, l.label)}</a>`)
    .join("\n");
  return `${MARK[0]}\n${pic(img, "GitHub profile card", ' width="100%"')}\n${buttons ? `\n<p align="center">\n${buttons}\n</p>\n` : ""}${MARK[1]}\n`;
}

/** Insert or refresh the block in an existing README (or start a new one). */
export function mergeReadme(existing: string | null, block: string) {
  if (!existing) return block;
  const [a, b] = MARK;
  const i = existing.indexOf(a);
  const j = existing.indexOf(b);
  if (i >= 0 && j > i) return existing.slice(0, i) + block.trimEnd() + existing.slice(j + b.length);
  return `${block}\n${existing}`;
}

// ── GitHub REST ──────────────────────────────────────────────────────────────

export class GitHubError extends Error {
  status: number;
  hint: string;
  constructor(status: number, message: string, hint: string) {
    super(message);
    this.status = status;
    this.hint = hint;
  }
}

async function call(token: string, method: string, path: string, body?: unknown): Promise<any> {
  const res = await fetch(path.startsWith("http") ? path : API + path, {
    method,
    headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", ...(body ? { "Content-Type": "application/json" } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (res.status === 204) return null;
  const json = await res.json().catch(() => ({}));
  if (!res.ok) {
    const scopes = res.headers.get("x-oauth-scopes");
    let hint = "";
    if (res.status === 401) hint = "The token is invalid or expired.";
    else if (res.status === 403 || res.status === 404)
      hint = /workflow/i.test(json.message ?? "") || (scopes !== null && !scopes.split(/,\s*/).includes("workflow"))
        ? "Pushing a workflow file needs the `workflow` scope (classic token) or the Workflows: write permission (fine-grained token)."
        : "Check that the token can write to this repository (classic: `repo` + `workflow`; fine-grained: Contents and Workflows write).";
    throw new GitHubError(res.status, json.message ?? res.statusText, hint);
  }
  return json;
}

export const api = {
  user: (t: string) => call(t, "GET", "/user"),
  repo: (t: string, o: string, r: string) => call(t, "GET", `/repos/${o}/${r}`).catch((e: GitHubError) => (e.status === 404 ? null : Promise.reject(e))),
  createRepo: (t: string, name: string) =>
    call(t, "POST", "/user/repos", { name, private: false, auto_init: true, description: "My GitHub profile" }),
  /** { text, sha } or null */
  file: async (t: string, o: string, r: string, path: string, ref: string): Promise<{ text: string; sha: string } | null> => {
    const j = await call(t, "GET", `/repos/${o}/${r}/contents/${path}?ref=${encodeURIComponent(ref)}`).catch((e: GitHubError) => (e.status === 404 ? null : Promise.reject(e)));
    if (!j || Array.isArray(j) || j.content === undefined) return null;
    return { text: dec.decode(fromB64(j.content)), sha: j.sha };
  },
  dispatch: (t: string, o: string, r: string, file: string, ref: string) => call(t, "POST", `/repos/${o}/${r}/actions/workflows/${file}/dispatches`, { ref }),
};

/**
 * One commit with all the files (git data API). files: [{ path, content: string | Uint8Array }].
 * Returns the commit. Empty repositories fall back to one contents-API commit per file.
 */
export async function commitFiles(token: string, owner: string, repo: string, branch: string, files: { path: string; content: string | Uint8Array }[], message: string, onProgress: (m: string) => void = () => {}) {
  const base = `/repos/${owner}/${repo}`;
  let head: any;
  try {
    head = await call(token, "GET", `${base}/git/ref/heads/${branch}`);
  } catch (e: any) {
    if (e.status !== 404 && e.status !== 409) throw e;
  }
  if (!head) {
    let last: any;
    for (const f of files) {
      onProgress(`Uploading ${f.path}`);
      last = await call(token, "PUT", `${base}/contents/${f.path}`, { message, content: b64(toBytes(f.content)), branch });
    }
    return last.commit;
  }
  const parent = await call(token, "GET", `${base}/git/commits/${head.object.sha}`);
  const tree: { path: string; mode: string; type: string; sha: string }[] = [];
  for (const f of files) {
    onProgress(`Uploading ${f.path}`);
    const blob = await call(token, "POST", `${base}/git/blobs`, { content: b64(toBytes(f.content)), encoding: "base64" });
    tree.push({ path: f.path, mode: "100644", type: "blob", sha: blob.sha });
  }
  onProgress("Creating commit");
  const t = await call(token, "POST", `${base}/git/trees`, { base_tree: parent.tree.sha, tree });
  const commit = await call(token, "POST", `${base}/git/commits`, { message, tree: t.sha, parents: [head.object.sha] });
  await call(token, "PATCH", `${base}/git/refs/heads/${branch}`, { sha: commit.sha });
  return commit;
}
